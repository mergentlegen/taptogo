import "server-only";

import {
  deviceTypes,
  operatingSystems,
  tapEventSchema,
  tapSources,
  type DeviceType,
  type OperatingSystem,
  type TapSource,
} from "@/features/analytics/schemas";

import type {
  DailyCardStatRepository,
  StatFilter,
  TapBreakdown,
  TapEventRepository,
  TapFilter,
} from "../analytics";
import { chunk, fail, fromRow, nullable, ok, one, rows, toInstant, toRow, type DbGetter } from "./support";

/** The filter arguments every tap RPC shares. */
function tapArgs(filter: TapFilter) {
  return {
    p_organization_id: filter.organizationId,
    p_card_ids: filter.cardIds ? [...filter.cardIds] : undefined,
    p_location_id: filter.locationId,
    p_employee_id: filter.employeeId,
  };
}

const zeroCounts = <K extends string>(keys: readonly K[]) =>
  Object.fromEntries(keys.map((key) => [key, 0])) as Record<K, number>;

/**
 * A card list that is too long for one request is split into chunks. Only for
 * methods whose results add up (counts) or merge (per-card maps) across chunks.
 */
const CARD_ID_CHUNK = 500;

export function supabaseTapEventRepository(db: DbGetter): TapEventRepository {
  return {
    async insert(event) {
      const c = await db();
      // The id is generated by the redirect, so a retry reuses it: a known id is ignored.
      const inserted = ok(
        await c
          .from("tap_events")
          .upsert(toRow(event), { onConflict: "id,occurred_at", ignoreDuplicates: true })
          .select(),
      );
      if (inserted && inserted.length > 0)
        return { event: fromRow(tapEventSchema, inserted[0]!), created: true };

      const existing = one(await c.from("tap_events").select("*").eq("id", event.id).limit(1).single());
      return { event: fromRow(tapEventSchema, existing), created: false };
    },

    async count({ range, kind = "valid", ...filter }) {
      const c = await db();
      const parts = filter.cardIds ? chunk(filter.cardIds, CARD_ID_CHUNK) : [undefined];
      const counts = await Promise.all(
        parts.map(async (cardIds) =>
          one(
            await c.rpc("tap_count", {
              p_from: range.from,
              p_to: range.to,
              p_kind: kind,
              ...tapArgs({ ...filter, cardIds }),
            }),
          ),
        ),
      );
      return counts.reduce((sum, n) => sum + n, 0);
    },

    async heatmap({ range, ...filter }, timeZone) {
      const c = await db();
      const data = rows(
        await c.rpc("tap_heatmap", {
          p_from: range.from,
          p_to: range.to,
          p_tz: timeZone,
          ...tapArgs(filter),
        }),
      );
      return data.map(({ weekday, hour, taps }) => ({ weekday, hour, taps }));
    },

    async breakdown({ range, ...filter }) {
      const c = await db();
      const result: TapBreakdown = {
        sources: zeroCounts(tapSources),
        operatingSystems: zeroCounts(operatingSystems),
        deviceTypes: zeroCounts(deviceTypes),
      };
      const data = rows(
        await c.rpc("tap_breakdown", { p_from: range.from, p_to: range.to, ...tapArgs(filter) }),
      );
      for (const { dimension, key, taps } of data) {
        if (dimension === "source") result.sources[key as TapSource] = taps;
        else if (dimension === "os") result.operatingSystems[key as OperatingSystem] = taps;
        else if (dimension === "deviceType") result.deviceTypes[key as DeviceType] = taps;
      }
      return result;
    },

    async lastTapByCard(filter) {
      const c = await db();
      const parts = filter.cardIds ? chunk(filter.cardIds, CARD_ID_CHUNK) : [undefined];
      const last: Record<string, string> = {};
      const results = await Promise.all(
        parts.map(async (cardIds) => rows(await c.rpc("last_tap_by_card", tapArgs({ ...filter, cardIds })))),
      );
      for (const row of results.flat()) last[row.card_id] = toInstant(row.last_tap_at);
      return last;
    },
  };
}

export function supabaseDailyCardStatRepository(db: DbGetter): DailyCardStatRepository {
  const range = ({ from, to, ...filter }: StatFilter) => ({
    p_from: from,
    p_to: to,
    ...tapArgs(filter),
  });

  return {
    async total(filter) {
      const c = await db();
      const [row] = rows(await c.rpc("daily_stat_totals", range(filter)));
      return {
        taps: row?.taps ?? 0,
        uniqueVisitors: row?.unique_visitors ?? 0,
        nfcTaps: row?.nfc_taps ?? 0,
        qrTaps: row?.qr_taps ?? 0,
      };
    },

    async totalsBy(filter, dimension) {
      const c = await db();
      const data = rows(await c.rpc("daily_stat_totals", { ...range(filter), p_dimension: dimension }));
      return data
        .map((row) => ({
          key: row.key,
          taps: row.taps,
          uniqueVisitors: row.unique_visitors,
          nfcTaps: row.nfc_taps,
          qrTaps: row.qr_taps,
        }))
        .sort((a, b) => a.key.localeCompare(b.key));
    },

    async increment(key, delta) {
      const c = await db();
      const { error } = await c.rpc("increment_daily_card_stat", {
        p_card_id: key.cardId,
        p_date: key.date,
        p_organization_id: key.organizationId,
        p_location_id: nullable(key.locationId),
        p_employee_id: nullable(key.employeeId),
        p_taps: delta.taps,
        p_unique_visitors: delta.uniqueVisitors,
        p_nfc_taps: delta.nfcTaps,
        p_qr_taps: delta.qrTaps,
      });
      if (error) fail(error);
    },
  };
}
