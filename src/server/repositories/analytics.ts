import type {
  DailyCardStat,
  DeviceType,
  OperatingSystem,
  TapEvent,
  TapSource,
} from "@/features/analytics/schemas";

import type { DateRange } from "./common";

export type TapFilter = {
  organizationId?: string;
  cardIds?: readonly string[];
  locationId?: string;
  employeeId?: string;
};

/** UTC instants (ISO strings), from inclusive, to exclusive. */
export type InstantRange = DateRange;

export type HeatmapCell = { weekday: number; hour: number; taps: number };

export type TapBreakdown = {
  sources: Record<TapSource, number>;
  operatingSystems: Record<OperatingSystem, number>;
  deviceTypes: Record<DeviceType, number>;
};

/**
 * Raw tap events. Analytical methods count only valid taps (no bots, no
 * duplicates). With Supabase they map to SQL aggregates / RPC functions.
 */
export interface TapEventRepository {
  /**
   * Idempotent on `id` (generated by the redirect, so retries reuse it):
   * a known id is not inserted again and `created` is false.
   */
  insert(event: TapEvent): Promise<{ event: TapEvent; created: boolean }>;
  /** Number of events in the range: valid taps (default), bots, duplicates or all of them. */
  count(
    filter: TapFilter & { range: InstantRange; kind?: "valid" | "bots" | "duplicates" | "all" },
  ): Promise<number>;
  /** Weekday (1 = Monday) × hour grid in `timeZone`; empty cells are omitted. */
  heatmap(filter: TapFilter & { range: InstantRange }, timeZone: string): Promise<HeatmapCell[]>;
  breakdown(filter: TapFilter & { range: InstantRange }): Promise<TapBreakdown>;
  /** Most recent valid tap per card (cards without taps are omitted). */
  lastTapByCard(filter: TapFilter): Promise<Record<string, string>>;
}

export type DailyStatKey = Pick<
  DailyCardStat,
  "cardId" | "organizationId" | "locationId" | "employeeId" | "date"
>;
export type DailyStatDelta = Pick<DailyCardStat, "taps" | "uniqueVisitors" | "nfcTaps" | "qrTaps">;

/** `from`/`to` are organization-local calendar dates, both inclusive. */
export type StatFilter = TapFilter & { from: string; to: string };
export type StatTotals = DailyStatDelta;
export type StatDimension = "date" | "cardId" | "locationId" | "employeeId" | "organizationId";
export type StatGroup = StatTotals & { key: string };

/**
 * Daily rollups are only ever read as sums (SQL `sum … group by`): the amount
 * of data a dashboard moves depends on the number of groups (days, cards…),
 * never on cards × days of stored rows.
 */
export interface DailyCardStatRepository {
  total(filter: StatFilter): Promise<StatTotals>;
  /** Sums per value of one dimension, sorted by key; rows where it is null are left out. */
  totalsBy(filter: StatFilter, dimension: StatDimension): Promise<StatGroup[]>;
  /** Upsert: adds `delta` to the (cardId, date) row, creating it if needed. */
  increment(key: DailyStatKey, delta: DailyStatDelta): Promise<void>;
}
